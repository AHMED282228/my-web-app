// Порядок языков в переключателях и языки с письмом справа налево
const LANG_ORDER = ["ru", "en", "ar", "hi"];
const RTL_LANGS = ["ar"];

function t(key) {
    // App объявлен через const в core.js и в window не попадает — проверяем через typeof
    const lang = (typeof App !== "undefined" && App.state.lang) || "ru";
    return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || I18N.ru[key] || key;
}

// Проставляет переводы всем элементам с data-i18n / data-i18n-ph
function applyI18n() {
    // Язык и направление письма: раскладка экрана остаётся прежней (график, шкалы
    // и цифры читаются слева направо в любом языке), а тексты на арабском
    // выравниваются справа — за это отвечает класс lang-rtl в стилях.
    const lang = (typeof App !== "undefined" && App.state.lang) || "ru";
    document.documentElement.lang = lang;
    document.documentElement.classList.toggle("lang-rtl", RTL_LANGS.indexOf(lang) !== -1);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
        el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
        el.placeholder = t(el.getAttribute("data-i18n-ph"));
    });
}
